class SmartOtpSetupScreen extends StatefulWidget {
  const SmartOtpSetupScreen({super.key, this.mandatory = false, this.onActivated});
  final bool mandatory;
  final VoidCallback? onActivated;
  @override
  State<SmartOtpSetupScreen> createState() => _SmartOtpSetupScreenState();
}

class _SmartOtpSetupScreenState extends State<SmartOtpSetupScreen> {
  final _pin = TextEditingController();
  final _repeat = TextEditingController();
  final _otp = TextEditingController();
  String? _deviceId;
  String? _channel;
  String? _error;
  bool _busy = false;

  @override
  void initState() {
    super.initState();
    _recoverPending();
  }

  Future<void> _recoverPending() async {
    final pending = await AppServices.smartOtpKeyStore.pending();
    if (mounted && pending?['deviceId'] != null) {
      setState(() { _deviceId = pending!['deviceId'].toString(); _channel = 'EMAIL_OR_FCM_DEMO'; });
    }
  }

  @override
  void dispose() {
    _pin.dispose(); _repeat.dispose(); _otp.dispose();
    super.dispose();
  }

  Future<void> _start() async {
    if (_busy) return;
    if (!RegExp(r'^\d{6}$').hasMatch(_pin.text) || _pin.text != _repeat.text) {
      setState(() => _error = 'Nhập hai mã PIN 6 chữ số giống nhau.');
      return;
    }
    setState(() { _busy = true; _error = null; });
    try {
      final pub = await AppServices.smartOtpKeyStore.createPending(_pin.text);
      final result = await AppServices.smartOtp.beginEnrollment(pub);
      final id = result['deviceId']?.toString() ?? '';
      if (id.isEmpty) throw StateError('Backend không trả mã thiết bị.');
      await AppServices.smartOtpKeyStore.bindPending(id);
      _pin.clear(); _repeat.clear();
      if (mounted) setState(() { _deviceId = id; _channel = result['channel']?.toString(); });
    } on ApiException catch (e) {
      if (mounted) setState(() => _error = e.message);
    } catch (e) {
      if (mounted) setState(() => _error = 'Không kích hoạt được Smart OTP: $e');
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  Future<void> _confirm() async {
    if (_busy || _deviceId == null || !RegExp(r'^\d{6}$').hasMatch(_otp.text)) return;
    setState(() { _busy = true; _error = null; });
    try {
      await AppServices.smartOtp.confirmEnrollment(_deviceId!, _otp.text);
      await AppServices.smartOtpKeyStore.activate(_deviceId!);
      if (mounted) {
        if (widget.onActivated != null) {
          widget.onActivated!();
        } else {
          Navigator.pop(context, true);
        }
      }
    } on ApiException catch (e) {
      if (mounted) setState(() => _error = e.message);
    } catch (e) {
      if (mounted) setState(() => _error = 'Không hoàn tất được: $e');
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) => PopScope(
    canPop: !widget.mandatory,
    child: Scaffold(
    appBar: AppBar(
      automaticallyImplyLeading: !widget.mandatory,
      title: const Text('Kích hoạt Smart OTP'),
    ),
    body: ListView(padding: const EdgeInsets.all(24), children: [
      const Text('Smart OTP cho chuyển tiền nội bộ, chuyển ngân hàng demo, rút tiền và lì xì.',
          style: TextStyle(fontSize: 16)),
      const SizedBox(height: 12),
      const Text('PIN dùng để bảo vệ khóa riêng trên thiết bị, KHÔNG gửi lên Backend. '
          'Chỉ dùng cho tài khoản và giao dịch mô phỏng.'),
      const SizedBox(height: 16),
      if (_error != null) Text(_error!, style: const TextStyle(color: Colors.red)),
      if (_deviceId == null) ...[
        TextField(controller: _pin, obscureText: true, maxLength: 6,
            keyboardType: TextInputType.number,
            inputFormatters: [FilteringTextInputFormatter.digitsOnly],
            decoration: const InputDecoration(labelText: 'PIN Smart OTP (6 số)')),
        TextField(controller: _repeat, obscureText: true, maxLength: 6,
            keyboardType: TextInputType.number,
            inputFormatters: [FilteringTextInputFormatter.digitsOnly],
            decoration: const InputDecoration(labelText: 'Nhập lại PIN')),
        FilledButton(onPressed: _busy ? null : _start,
            child: Text(_busy ? 'Đang xử lý...' : 'Đăng ký thiết bị')),
      ] else ...[
        Text(_channel == 'EMAIL' ? 'Mã xác minh đã gửi về email.' :
          'Mã xác minh sẽ được gửi qua thông báo FCM demo (hoặc email nếu có).'),
        const SizedBox(height: 8),
        TextField(controller: _otp, maxLength: 6, keyboardType: TextInputType.number,
            inputFormatters: [FilteringTextInputFormatter.digitsOnly],
            decoration: const InputDecoration(labelText: 'OTP kích hoạt thiết bị')),
        FilledButton(onPressed: _busy ? null : _confirm,
            child: Text(_busy ? 'Đang xác minh...' : 'Kích hoạt Smart OTP')),
        const SizedBox(height: 6),
        TextButton(
          onPressed: _busy ? null : () async {
            await AppServices.smartOtpKeyStore.clearPending();
            _otp.clear();
            if (mounted) setState(() { _deviceId=null; _channel=null; _error=null; });
          },
          child: const Text('Bắt đầu lại (nếu OTP đã hết hạn, sau khoảng 5 phút)'),
        ),
      ],
    ]),
  ));
}


/// Device management: authentication is required; revocation disables future
/// signatures, but recovery should require stronger re-auth outside of demos.
class SmartOtpManagementScreen extends StatefulWidget {
  const SmartOtpManagementScreen({super.key});
  @override
  State<SmartOtpManagementScreen> createState() => _SmartOtpManagementScreenState();
}
class _SmartOtpManagementScreenState extends State<SmartOtpManagementScreen> {
  Map<String,dynamic>? _status;
  bool _busy=false;
  String? _error;
  @override void initState() { super.initState(); _load(); }
  Future<void> _load() async {
    setState(() => _busy=true);
    try { final value=await AppServices.smartOtp.status(); if(mounted) setState(() => _status=value); }
    on ApiException catch(e) { if(mounted) setState(() => _error=e.message); }
    finally { if(mounted) setState(() => _busy=false); }
  }
  Future<void> _revoke() async {
    if(_status?['active']!=true) return;
    final approved=await showDialog<bool>(context:context,builder:(ctx)=>AlertDialog(
      title: const Text('Thu hồi Smart OTP?'),
      content: const Text('Sau khi thu hồi, các giao dịch mới sẽ yêu cầu kích hoạt thiết bị và OTP xác minh lại.'),
      actions:[TextButton(onPressed:()=>Navigator.pop(ctx,false),child:const Text('Hủy')),
        FilledButton(onPressed:()=>Navigator.pop(ctx,true),child:const Text('Thu hồi'))],
    ));
    if(approved!=true || !mounted) return;
    setState(() => _busy=true);
    try {
      final id=_status!['deviceId'].toString();
      await AppServices.smartOtp.revoke(id);
      await AppServices.smartOtpKeyStore.clear(id);
      await _load();
    } on ApiException catch(e) { if(mounted) setState(() => _error=e.message); }
    finally { if(mounted) setState(() => _busy=false); }
  }
  @override Widget build(BuildContext context) => Scaffold(
    appBar: AppBar(title: const Text('Smart OTP AnPay')),
    body: ListView(padding:const EdgeInsets.all(24),children: [
      if(_busy) const LinearProgressIndicator(),
      if(_error!=null) Text(_error!,style:const TextStyle(color: Colors.red)),
      Text(_status?['active']==true ? 'Smart OTP đang hoạt động' : 'Smart OTP chưa kích hoạt',
          style:const TextStyle(fontSize:20,fontWeight: FontWeight.bold)),
      const SizedBox(height:16),
      if(_status?['active']==true) ...[
        Text('Thiết bị: ${_status?['deviceId'] ?? ''}'),
        const SizedBox(height:10),
        FilledButton(onPressed:_busy?null:_revoke,child:const Text('Thu hồi thiết bị')),
      ] else FilledButton(onPressed:_busy?null:() async {
        await SmartOtpFlow.ensureActivated(context);
        if(mounted) _load();
