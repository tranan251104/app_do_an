/// A shared, two-step Smart OTP confirmation screen for every money movement.
/// 1) Unlock the device transaction key with the 6-digit PIN.
/// 2) Display the 6-digit, transaction-bound code and let the user approve.
/// PIN stays on the device. Backend verifies the Ed25519 signature AND code.
class SmartOtpFlow {
  SmartOtpFlow._();

  static Future<bool> ensureActivated(BuildContext context) async {
    try {
      final status = await AppServices.smartOtp.status();
      final active = status['active'] == true;
      if (active) {
        final local = await AppServices.smartOtpKeyStore.hasLocalDevice(status['deviceId'].toString());
        if (local) return true;
        if (await AppServices.smartOtpKeyStore.recoverConfirmedDevice(status['deviceId'].toString())) return true;
        if (context.mounted) {
          _toast(context, 'Thiết bị đã kích hoạt trên tài khoản nhưng không có khóa cục bộ. '
              'Vào Cá nhân → Quản lý Smart OTP → Thu hồi thiết bị cũ rồi kích hoạt lại.');
        }
        return false;
      }
      if (!context.mounted) return false;
      final me=await AppServices.user.me();
      if ((me['email']?.toString().trim() ?? '').isEmpty) {
        final registered=await NotificationService.registerCurrentDevice(source: 'smart_otp_activation');
        if(!registered) {
          if(context.mounted) _toast(context,'Cần đăng ký thiết bị FCM để nhận OTP kích hoạt Smart OTP demo.');
          return false;
        }
      }
      if(!context.mounted) return false;
      final result = await Navigator.of(context).push<bool>(
        MaterialPageRoute(builder: (_) => const SmartOtpSetupScreen()),
      );
      return result == true;
    } on ApiException catch (e) {
      if (context.mounted) _toast(context, e.message);
      return false;
    } catch (_) {
      if (context.mounted) _toast(context, 'Không kết nối được hệ thống Smart OTP.');
      return false;
    }
  }

  /// Returns the SAME proof contract used by all transfer / withdrawal APIs.
  /// No backend change is needed to show the six-digit OTP as a second step.
  static Future<Map<String, String>?> authorize(
      BuildContext context, String transactionId) async {
    try {
      final auth = await AppServices.smartOtp.authorization(transactionId);
      if (!context.mounted) return null;

      final deviceId = auth['deviceId']?.toString() ?? '';
      final message = auth['message']?.toString() ?? '';
      final expiresAt = DateTime.tryParse(auth['expiresAt']?.toString() ?? '')?.toLocal();
      if (deviceId.isEmpty || message.isEmpty || expiresAt == null) {
        throw StateError('Yêu cầu xác thực Smart OTP chưa đầy đủ.');
      }
      if (!expiresAt.isAfter(DateTime.now())) {
        _toast(context, 'Yêu cầu xác thực đã hết hạn. Hãy tạo lại giao dịch.');
        return null;
      }

      // Step 1: show an MB-like PIN sheet; perform signing INSIDE that sheet.
      // Failed PIN stays on the sheet so the user can retry without re-fetching.
      final signature = await showModalBottomSheet<String>(
        context: context,
        isScrollControlled: true,
        useSafeArea: true,
        backgroundColor: Colors.transparent,
        builder: (_) => _SmartOtpPinSheet(
          deviceId: deviceId,
          message: message,
          authorization: auth,
        ),
      );
      if (signature == null || !context.mounted) return null;
      if (!expiresAt.isAfter(DateTime.now())) {
        _toast(context, 'Smart OTP đã hết hạn. Hãy tạo lại yêu cầu xác thực.');
        return null;
      }

      // The backend independently derives the same six digits from the signature.
      // These are NOT six random digits generated by the Flutter UI.
      final sha = await Sha256().hash(base64Decode(signature));
      final d = sha.bytes;
      final number = ((d[0] << 24) | (d[1] << 16) | (d[2] << 8) | d[3]) & 0xffffffff;
      final code = (number % 1000000).toString().padLeft(6, '0');
      if (!context.mounted) return null;

      // Step 2: show the generated code and a real server-based countdown.
      // Pressing 'Xác thực' automatically submits the proof to the existing
      // service/controller caller; users do NOT type the code manually.
      final approved = await showModalBottomSheet<bool>(
        context: context,
        isScrollControlled: true,
        useSafeArea: true,
        backgroundColor: Colors.transparent,
        builder: (_) => _SmartOtpCodeSheet(
          code: code,
          authorization: auth,
          expiresAt: expiresAt,
        ),
      );
      if (approved != true || !context.mounted) return null;
      if (!expiresAt.isAfter(DateTime.now())) {
        _toast(context, 'Mã Smart OTP hết hạn. Hãy tạo lại yêu cầu xác thực.');
        return null;
      }

      return {'deviceId': deviceId, 'signature': signature, 'smartOtpCode': code};
    } on ApiException catch (e) {
      if (context.mounted) _toast(context, e.message);
      return null;
    } catch (e) {
      if (context.mounted) {
        _toast(context, e is StateError ? e.message.toString() : 'Không thể tạo Smart OTP.');
      }
      return null;
    }
  }

  static void _toast(BuildContext context, String message) {
    ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(message)));
  }
}

/// Step 1 — six empty circles, numeric keyboard, auto-advance on 6 digits.
class _SmartOtpPinSheet extends StatefulWidget {
  const _SmartOtpPinSheet({
    required this.deviceId,
    required this.message,
    required this.authorization,
  });
  final String deviceId;
  final String message;
  final Map<String, dynamic> authorization;

  @override
  State<_SmartOtpPinSheet> createState() => _SmartOtpPinSheetState();
}

class _SmartOtpPinSheetState extends State<_SmartOtpPinSheet> {
  final TextEditingController _pin = TextEditingController();
  final FocusNode _focus = FocusNode();
  bool _working = false;
  String? _error;

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) _focus.requestFocus();
    });
  }

  @override
  void dispose() {
    _pin.dispose();
    _focus.dispose();
    super.dispose();
  }

  Future<void> _sign() async {
    if (_working || _pin.text.length != 6) return;
    final pin = _pin.text;
    setState(() { _working = true; _error = null; });
    try {
      final signature = await AppServices.smartOtpKeyStore.sign(
        widget.deviceId, widget.message, pin,
      );
      if (mounted) {
        _focus.unfocus();
        Navigator.of(context).pop(signature);
      }
    } catch (e) {
      if (!mounted) return;
      _pin.clear();
      setState(() {
        _error = e is StateError ? e.message.toString() : 'Không thể xác thực PIN.';
      });
      _focus.requestFocus();
    } finally {
      if (mounted) setState(() => _working = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    const ink = Color(0xFF173DA5);
    final amount = NumberFormat.decimalPattern('vi').format(
        widget.authorization['amount'] ?? 0);
    return Container(
      decoration: const BoxDecoration(
        color: Color(0xFFF8F9FE),
        borderRadius: BorderRadius.vertical(top: Radius.circular(28)),
      ),
      child: AnimatedPadding(
        duration: const Duration(milliseconds: 160),
        curve: Curves.easeOut,
        padding: EdgeInsets.fromLTRB(
          24, 14, 24, 22 + MediaQuery.viewInsetsOf(context).bottom,
        ),
        child: SingleChildScrollView(
          child: Column(mainAxisSize: MainAxisSize.min, children: [
            const _SmartOtpHandle(),
            const SizedBox(height: 24),
            const Text('Xác thực Smart OTP',
                style: TextStyle(fontSize: 23, fontWeight: FontWeight.w700,
                    color: ink)),
            const SizedBox(height: 25),
            const Text('Nhập mã PIN Smart OTP để tạo mã xác thực giao dịch',
                textAlign: TextAlign.center,
                style: TextStyle(fontSize: 16, height: 1.5,
                    color: Color(0xFF5B6270))),
            const SizedBox(height: 14),
            Text('$amount VNĐ',
                style: const TextStyle(fontSize: 19, fontWeight: FontWeight.w700,
                    color: ink)),
            const SizedBox(height: 24),
            // Invisible native text field handles the system numeric keyboard.
            // Only the six PIN indicator circles are rendered visibly.
            GestureDetector(
              onTap: () => _focus.requestFocus(),
              child: SizedBox(
                height: 62,
                child: Stack(children: [
                  Center(child: AnimatedBuilder(
                    animation: _pin,
                    builder: (_, __) => Row(
                      mainAxisAlignment: MainAxisAlignment.spaceEvenly,
                      children: List.generate(6, (index) => Container(
                        width: 43, height: 43,
                        decoration: BoxDecoration(
                          color: index < _pin.text.length
                              ? const Color(0xFFE6EDFF) : Colors.white,
                          shape: BoxShape.circle,
                          border: Border.all(
                            color: index < _pin.text.length
                                ? ink : const Color(0xFFB5C2DF),
                            width: 1.6,
                          ),
                        ),
                        child: index < _pin.text.length
                            ? const Center(child: CircleAvatar(
                                radius: 5, backgroundColor: ink))
                            : null,
                      )),
                    ),
                  )),
                  Positioned.fill(child: Opacity(
                    opacity: 0,
                    child: TextField(
                      controller: _pin,
                      focusNode: _focus,
                      enabled: !_working,
                      autofocus: true,
                      keyboardType: TextInputType.number,
                      textInputAction: TextInputAction.done,
                      obscureText: true,
                      enableSuggestions: false,
                      autocorrect: false,
                      enableInteractiveSelection: false,
                      maxLength: 6,
                      inputFormatters: [FilteringTextInputFormatter.digitsOnly],
                      decoration: const InputDecoration(
                          counterText: '', border: InputBorder.none),
                      onChanged: (value) {
                        if (_error != null) setState(() => _error = null);
                        if (value.length == 6) _sign();
                      },
                      onSubmitted: (_) => _sign(),
                    ),
                  )),
                ]),
              ),
            ),
            if (_error != null) ...[
              const SizedBox(height: 12),
              Text(_error!, textAlign: TextAlign.center,
                style: const TextStyle(color: Color(0xFFC62828))),
            ],
            if (_working) ...[
              const SizedBox(height: 14),
              const CircularProgressIndicator(strokeWidth: 2),
              const SizedBox(height: 8),
              const Text('Đang tạo Smart OTP...'),
            ],
            const SizedBox(height: 8),
            TextButton(
              onPressed: _working ? null : () => Navigator.of(context).pop(),
              child: const Text('Hủy'),
            ),
          ]),
        ),
      ),
    );
  }
}

/// Step 2 — six-digit code, actual challenge expiry and one-tap confirmation.
class _SmartOtpCodeSheet extends StatefulWidget {
  const _SmartOtpCodeSheet({
    required this.code,
    required this.authorization,
    required this.expiresAt,
  });
  final String code;
  final Map<String, dynamic> authorization;
  final DateTime expiresAt;

  @override
  State<_SmartOtpCodeSheet> createState() => _SmartOtpCodeSheetState();
}

class _SmartOtpCodeSheetState extends State<_SmartOtpCodeSheet> {
  Timer? _ticker;
  int _remainingSeconds = 0;

  @override
  void initState() {
    super.initState();
    _updateRemaining();
    _ticker = Timer.periodic(const Duration(seconds: 1), (_) {
      if (mounted) _updateRemaining();
    });
  }

  void _updateRemaining() {
    final ms = widget.expiresAt.difference(DateTime.now()).inMilliseconds;
    final seconds = ms <= 0 ? 0 : (ms + 999) ~/ 1000;
    if (mounted) setState(() => _remainingSeconds = seconds);
  }

  @override
  void dispose() {
    _ticker?.cancel();
    super.dispose();
  }

  void _approve() {
    if (_remainingSeconds <= 0 || !widget.expiresAt.isAfter(DateTime.now())) {
      return;
    }
    Navigator.of(context).pop(true);
  }

  @override
  Widget build(BuildContext context) {
    const ink = Color(0xFF173DA5);
    final expired = _remainingSeconds <= 0;
    final mm = (_remainingSeconds ~/ 60).toString().padLeft(2, '0');
    final ss = (_remainingSeconds % 60).toString().padLeft(2, '0');
    final amount = NumberFormat.decimalPattern('vi').format(
        widget.authorization['amount'] ?? 0);
    return Container(
      decoration: const BoxDecoration(
        color: Color(0xFFF8F9FE),
        borderRadius: BorderRadius.vertical(top: Radius.circular(28)),
      ),
      padding: EdgeInsets.fromLTRB(
        24, 14, 24, 24 + MediaQuery.paddingOf(context).bottom,
      ),
      child: Column(mainAxisSize: MainAxisSize.min, children: [
        const _SmartOtpHandle(),
        const SizedBox(height: 24),
        const Text('Xác thực Smart OTP',
            style: TextStyle(fontSize: 23, fontWeight: FontWeight.w700,
                color: ink)),
        const SizedBox(height: 26),
        const Text('Mã xác thực giao dịch',
            style: TextStyle(fontSize: 17, color: Color(0xFF666C78))),
        const SizedBox(height: 16),
        Row(children: List.generate(6, (i) => Expanded(
          child: Container(
            height: 64,
            margin: const EdgeInsets.symmetric(horizontal: 3),
            alignment: Alignment.center,
            decoration: BoxDecoration(
              color: const Color(0xFFEAF0FF),
              borderRadius: BorderRadius.circular(9),
            ),
            child: Text(widget.code[i], style: const TextStyle(
              fontSize: 30, fontWeight: FontWeight.bold, color: ink,
            )),
          ),
        ))),
        const SizedBox(height: 20),
        Text(
          expired ? 'Mã đã hết hạn' : 'Mã có hiệu lực trong $mm:$ss',
          style: TextStyle(fontSize: 16, color: expired ? Colors.red : ink,
              fontWeight: FontWeight.w600),
        ),
        const SizedBox(height: 14),
        Text('Số tiền: $amount VNĐ',
            style: const TextStyle(fontSize: 15, color: Color(0xFF626B7B))),
        Text('${widget.authorization['recipient'] ?? ''}',
            maxLines: 2, overflow: TextOverflow.ellipsis,
            textAlign: TextAlign.center,
            style: const TextStyle(fontSize: 14, color: Color(0xFF626B7B))),
        const SizedBox(height: 20),
        Text(expired
            ? 'Vui lòng quay lại và tạo lại yêu cầu xác thực.'
            : 'Bấm Xác thực để tự động gửi mã, không cần nhập lại.',
            textAlign: TextAlign.center,
            style: const TextStyle(fontSize: 15, color: Color(0xFF626B7B))),
        const SizedBox(height: 22),
        SizedBox(
          width: double.infinity,
          height: 52,
          child: FilledButton(
            onPressed: expired ? null : _approve,
            style: FilledButton.styleFrom(
              backgroundColor: ink,
              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
            ),
            child: const Text('Xác thực',
                style: TextStyle(fontSize: 18, fontWeight: FontWeight.w700)),
          ),
        ),
        TextButton(
          onPressed: () => Navigator.of(context).pop(false),
          child: const Text('Hủy giao dịch'),
        ),
      ]),
    );
  }
}

